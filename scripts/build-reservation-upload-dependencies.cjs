// Local-only source extraction. Does not read credentials or contact any service.
const fs=require('node:fs');
const {createHash}=require('node:crypto');
const {statements,withoutComments}=require('./build-reservation-upgrade.cjs');
const output='supabase/migrations/20261102070521_reservation_private_upload_dependencies.sql';
const sources=['20261013000500_request_bound_private_uploads.sql','20261013000800_account_erasure.sql'];
const literal=value=>"'"+value.replaceAll("'","''")+"'";
function build(){
  const parts=[`-- GENERATED by scripts/build-reservation-upload-dependencies.cjs
-- Reservation proof dependencies only. No account erasure or owner workflow is run.
begin;
set local lock_timeout='5s';
set local statement_timeout='60s';`];
  const provenance=[];
  for(const name of sources){
    const bytes=fs.readFileSync('supabase/migrations/'+name);
    provenance.push({name,sha256:createHash('sha256').update(bytes).digest('hex')});
    for(const original of statements(bytes.toString('utf8'))){
      let sql=withoutComments(original);
      const upload=name.includes('request_bound');
      const include=upload
        ? /^(?:create table public\.(?:owner_application_drafts|private_upload_admissions)\b|create index (?:owner_application_drafts|private_upload_admissions)_|alter table public\.(?:owner_application_drafts|private_upload_admissions) enable|(?:revoke all|grant select|grant all) on public\.(?:owner_application_drafts|private_upload_admissions)|create policy owner_application_drafts_read_own|create function public\.(?:claim_private_upload|list_expired_private_uploads)\(|(?:revoke all|grant execute) on function public\.(?:claim_private_upload|list_expired_private_uploads)\()/i.test(sql)
        : /^(?:create table public\.account_deletion_requests\b|alter table public\.account_deletion_requests enable|(?:revoke all|grant select|grant all) on public\.account_deletion_requests|create policy deletion_read_own|create function public\.account_is_active\()/i.test(sql);
      if(!include)continue;
      sql=sql.replace(/^create table /i,'create table if not exists ').replace(/^create index /i,'create index if not exists ');
      const policy=sql.match(/^create policy (\w+) on ([\w.]+)/i);
      if(policy)sql=`drop policy if exists ${policy[1]} on ${policy[2]};\n${sql}`;
      const fn=sql.match(/^create function public\.(\w+)\(/i);
      if(fn){
        const signatures={claim_private_upload:'uuid,text,uuid',list_expired_private_uploads:'integer',account_is_active:'uuid'};
        const signature=`public.${fn[1]}(${signatures[fn[1]]})`;
        // Preserve existing implementations and their account protections exactly.
        sql=`do $install$ begin
  if to_regprocedure(${literal(signature)}) is null then
    execute ${literal(sql)};
    revoke all on function ${signature} from public,anon,authenticated;
    grant execute on function ${signature} to service_role;
  end if;
end $install$;`;
      }
      parts.push(`-- Source: ${name}\n${sql}`);
    }
  }
  parts.push(`-- Read-only recovery selection: legacy rows without durable requests must
-- remain visible for manual reconciliation without starving newer safe retries.
create or replace function public.get_payment_recovery_batch(batch_size integer default 5)
returns jsonb language sql stable security definer set search_path='' as $recovery$
  select jsonb_build_object(
    'attempts',coalesce((select jsonb_agg(to_jsonb(p) order by p.created_at,p.id) from (
      select * from public.reservation_payments
      where attempt_state in ('creating','reconciliation_required') and status<>'paid'
        and checkout_request is not null and created_at>now()-interval '23 hours'
      order by created_at,id limit least(greatest(batch_size,1),5)
    ) p),'[]'::jsonb),
    'manual_count',(select count(*) from public.reservation_payments
      where attempt_state in ('creating','reconciliation_required') and status<>'paid'
        and (status='pending' or checkout_request is not null)
        and (checkout_request is null or created_at<=now()-interval '23 hours'))
  );
$recovery$;
revoke all on function public.get_payment_recovery_batch(integer) from public,anon,authenticated;
grant execute on function public.get_payment_recovery_batch(integer) to service_role;
revoke all on public.private_upload_admissions from public,anon,authenticated;
revoke all on public.owner_application_drafts,public.account_deletion_requests from public;
notify pgrst,'reload schema';
commit;`);
  return {sql:parts.join('\n\n')+'\n',provenance};
}
if(require.main===module){
  const {sql,provenance}=build();
  if(process.argv.includes('--check')){
    if(fs.readFileSync(output,'utf8')!==sql)throw new Error('Private upload dependencies differ from their sources');
  }else{
    fs.writeFileSync(output,sql);
    fs.writeFileSync('tests/remediation/evidence/reservation-upload-sources.json',JSON.stringify({output,sources:provenance},null,2)+'\n');
  }
  console.log('Reservation upload dependency migration matches reviewed source extraction.');
}
module.exports={build,output};
